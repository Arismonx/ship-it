// typeScriptTools renders the result types of the MCP tools for the VS Code
// extension, from the JSON Schemas the server publishes as outputSchema.
func typeScriptTools() []byte {
	var b strings.Builder
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n// Copyright 2026 Grégoire Favreau\n\n")
	b.WriteString("// Code generated by `go run ./tools/gen` from the outputSchema of `ship mcp`. DO NOT EDIT.\n\n")
	types := mcp.ToolResultTypes()
	names := make([]string, 0, len(types))
	for name := range types {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		fmt.Fprintf(&b, "export type %s = %s;\n\n", resultTypeName(name), tsType(schema.For(types[name]), ""))
	}
	b.WriteString("/** The result type of each tool, by tool name. */\nexport interface ToolResults {\n")
	for _, name := range names {
		fmt.Fprintf(&b, "  %s: %s;\n", name, resultTypeName(name))
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

// resultTypeName turns ship_status into ShipStatusResult.
func resultTypeName(tool string) string {
	var b strings.Builder
	for _, part := range strings.Split(tool, "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String() + "Result"
}

func tsType(s map[string]any, indent string) string {
	if alternatives, ok := s["anyOf"].([]any); ok {
		parts := make([]string, 0, len(alternatives))
		for _, a := range alternatives {
			parts = append(parts, tsType(a.(map[string]any), indent))
		}
		return strings.Join(parts, " | ")
	}
	var kinds []string
	switch t := s["type"].(type) {
	case string:
		kinds = []string{t}
	case []string:
		kinds = t
	}
	var parts []string
	for _, k := range kinds {
		switch k {
		case "null":
			parts = append(parts, "null")
		case "string":
			parts = append(parts, "string")
		case "integer", "number":
			parts = append(parts, "number")
		case "boolean":
			parts = append(parts, "boolean")
		case "array":
			item := tsType(s["items"].(map[string]any), indent)
			if strings.Contains(item, " | ") {
				item = "(" + item + ")" // T | null[] would mean something else
			}
			parts = append(parts, item+"[]")
		case "object":
			parts = append(parts, tsObject(s, indent))
		}
	}
	if len(parts) == 0 {
		return "unknown"
	}
	return strings.Join(parts, " | ")
}

func tsObject(s map[string]any, indent string) string {
	properties, _ := s["properties"].(map[string]any)
	if len(properties) == 0 {
		if extra, ok := s["additionalProperties"].(map[string]any); ok {
			return "Record<string, " + tsType(extra, indent) + ">"
		}
		return "Record<string, unknown>"
	}
	required, _ := s["required"].([]string)
	keys := make([]string, 0, len(properties))
	for k := range properties {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("{\n")
	for _, k := range keys {
		p := properties[k].(map[string]any)
		if doc, ok := p["description"].(string); ok {
			fmt.Fprintf(&b, "%s  /** %s */\n", indent, doc)
		}
		optional := "?"
		if slices.Contains(required, k) {
			optional = ""
		}
		fmt.Fprintf(&b, "%s  %s%s: %s;\n", indent, k, optional, tsType(p, indent+"  "))
	}
	b.WriteString(indent + "}")
	return b.String()
}
