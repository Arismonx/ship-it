package benchdata

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

// RepoOptions shape a generated repository.
type RepoOptions struct {
	// Files are tracked at the tip; Commits is the length of the history.
	Files, Commits int
	// Modified tracked files and new Untracked files are the work in progress.
	Modified, Untracked int
}

// Repository names of a generated repository.
const (
	// Branch is checked out, three commits ahead of origin/main and one
	// ahead of its upstream origin/<Branch>.
	Branch = "feat/bench"
	// RemoteURL is origin's URL: a GitHub repository that is never reached.
	RemoteURL = "https://github.com/acme/widget.git"
)

// repoConfig is the repository configuration of the generated project: a
// preset, a setting and two overrides, the shape docs/reference/configuration.md recommends.
const repoConfig = `{
  // Generated by benchdata.
  "extends": ["ship-it:recommended"],
  "ship": {"pullRequest": {"maxLines": 600}},
  "overrides": [
    {"paths": ["docs/**", "*.md"], "ship": {"gates": {"enabled": false}}},
    {"paths": ["apps/web/**"], "ship": {"pullRequest": {"maxLines": 800}}}
  ]
}
`

// NewRepository creates in dir (empty or missing) a repository of
// o.Files files and o.Commits commits, written by one `git fast-import`,
// with a work in progress of o.Modified changed and o.Untracked new files.
// Every remote ref is local: nothing is fetched. The tree is the same on
// every run.
func NewRepository(dir string, o RepoOptions) error {
	if o.Commits < 4 || o.Files < o.Modified {
		return fmt.Errorf("benchdata: need at least 4 commits and as many files as modified ones")
	}
	run := func(stdin []byte, args ...string) error {
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		if stdin != nil {
			cmd.Stdin = bytes.NewReader(stdin)
		}
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("git %s: %v: %s", strings.Join(args, " "), err, out)
		}
		return nil
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	if err := run(nil, "init", "--quiet", "--initial-branch=main"); err != nil {
		return err
	}
	for _, kv := range [][2]string{
		{"user.name", "ship-it bench"}, {"user.email", "bench@example.invalid"}, {"commit.gpgsign", "false"},
		{"core.autocrlf", "false"}, {"remote.origin.url", RemoteURL},
		{"remote.origin.fetch", "+refs/heads/*:refs/remotes/origin/*"},
		{"branch." + Branch + ".remote", "origin"}, {"branch." + Branch + ".merge", "refs/heads/" + Branch},
	} {
		if err := run(nil, "config", kv[0], kv[1]); err != nil {
			return err
		}
	}
	if err := run(history(o), "fast-import", "--quiet", "--done"); err != nil {
		return err
	}
	if err := run(nil, "symbolic-ref", "HEAD", "refs/heads/"+Branch); err != nil {
		return err
	}
	if err := run(nil, "symbolic-ref", "refs/remotes/origin/HEAD", "refs/remotes/origin/main"); err != nil {
		return err
	}
	if err := run(nil, "reset", "--quiet", "--hard"); err != nil {
		return err
	}
	// A checkout is older than the work in progress: files last changed a
	// day ago, as git's index knows them (refreshed, so that status does not
	// rehash the tree).
	if err := age(dir, Paths(o.Files-1), ".github/ship.json"); err != nil {
		return err
	}
	if err := run(nil, "update-index", "-q", "--refresh"); err != nil {
		return err
	}
	return workInProgress(dir, o)
}

// checkoutTime is the modification time of the generated files.
var checkoutTime = time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)

func age(dir string, paths []string, more ...string) error {
	for _, p := range append(paths, more...) {
		if err := os.Chtimes(filepath.Join(dir, filepath.FromSlash(p)), checkoutTime, checkoutTime); err != nil {
			return err
		}
	}
	return nil
}

// history is the fast-import stream: a first commit with every file, then
// commits changing five files each, on Branch; main and origin/main stop
// three commits before its tip, origin/<Branch> one before.
func history(o RepoOptions) []byte {
	r := newRand()
	paths := Paths(o.Files - 1)
	var b bytes.Buffer
	data := func(s string) { fmt.Fprintf(&b, "data %d\n%s\n", len(s), s) }
	for i := 1; i <= o.Commits; i++ {
		when := 1_767_225_600 + int64(i)*3600 // 2026-01-01, one commit an hour
		fmt.Fprintf(&b, "commit refs/heads/%s\nmark :%d\n", Branch, i)
		fmt.Fprintf(&b, "author ship-it bench <bench@example.invalid> %d +0000\n", when)
		fmt.Fprintf(&b, "committer ship-it bench <bench@example.invalid> %d +0000\n", when)
		if i == 1 {
			data("🎉 chore: initial commit")
			b.WriteString("M 100644 inline .github/ship.json\n")
			data(repoConfig)
			for _, p := range paths {
				fmt.Fprintf(&b, "M 100644 inline %s\n", p)
				data(FileContent(r, 40))
			}
			continue
		}
		data(fmt.Sprintf("✨ feat(core): change %d", i))
		fmt.Fprintf(&b, "from :%d\n", i-1)
		for range 5 {
			fmt.Fprintf(&b, "M 100644 inline %s\n", paths[r.IntN(len(paths))])
			data(FileContent(r, 40))
		}
	}
	fmt.Fprintf(&b, "reset refs/heads/main\nfrom :%d\n\n", o.Commits-3)
	fmt.Fprintf(&b, "reset refs/remotes/origin/main\nfrom :%d\n\n", o.Commits-3)
	fmt.Fprintf(&b, "reset refs/remotes/origin/%s\nfrom :%d\n\ndone\n", Branch, o.Commits-1)
	return b.Bytes()
}

// workInProgress changes six lines in each of the first o.Modified source
// files and adds o.Untracked files.
func workInProgress(dir string, o RepoOptions) error {
	r := newRand()
	for i, p := range Paths(o.Files - 1)[:o.Modified] {
		full := filepath.Join(dir, filepath.FromSlash(p))
		content, err := os.ReadFile(full)
		if err != nil {
			return err
		}
		lines := strings.Split(string(content), "\n")
		for k := range 6 {
			lines[(i+k*5)%(len(lines)-1)] = Line(r) + " // changed"
		}
		if err := os.WriteFile(full, []byte(strings.Join(lines, "\n")), 0o644); err != nil {
			return err
		}
	}
	for i := range o.Untracked {
		full := filepath.Join(dir, "apps", "api", "internal", "fresh", fmt.Sprintf("new_%d.go", i))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(full, []byte(FileContent(r, 30)), 0o644); err != nil {
			return err
		}
	}
	return nil
}
