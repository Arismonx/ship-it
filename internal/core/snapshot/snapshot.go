package snapshot

import (
	"path"
	"strings"
)

// ChangeStatus says what happened to a file.
type ChangeStatus int

// Change statuses.
const (
	Modified ChangeStatus = iota
	Added
	Deleted
	Renamed
)

// Category groups files by the role they play in a change.
type Category int

// Categories, from the most to the least significant for a commit title.
const (
	SourceCode Category = iota
	Tests
	Documentation
	Stylesheets
	ContinuousIntegration
	Dependencies
	Configuration
	Assets
)

// File is one changed file, ready for planning.
type File struct {
	FileDiff
	Category Category
	// Generated is true for lockfiles and files marked linguist-generated.
	Generated bool
}

// AddedCount and RemovedCount are the line counts used as weights.
func (f File) AddedCount() int   { return len(f.Added) }
func (f File) RemovedCount() int { return len(f.Removed) }

// Snapshot is the work in progress, as the planner sees it.
type Snapshot struct {
	Files []File
}

// Options tunes classification for a repository.
type Options struct {
	// GeneratedPaths are paths marked linguist-generated in .gitattributes.
	GeneratedPaths map[string]bool
}

// New classifies parsed diffs into a snapshot.
func New(diffs []FileDiff, opts Options) Snapshot {
	files := make([]File, 0, len(diffs))
	for _, d := range diffs {
		files = append(files, File{
			FileDiff:  d,
			Category:  Categorize(d.Path),
			Generated: opts.GeneratedPaths[d.Path] || IsLockfile(d.Path),
		})
	}
	return Snapshot{Files: files}
}

// lockfiles are generated by package managers; they must never drive a title.
