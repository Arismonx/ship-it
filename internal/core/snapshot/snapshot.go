// Categorize classifies a repository-relative path. Tests win over source
// code, CI and dependency files over configuration.
func Categorize(p string) Category {
	lower := strings.ToLower(p)
	base := path.Base(lower)
	ext := path.Ext(base)
	switch {
	case isTestPath(lower, base):
		return Tests
	case strings.HasPrefix(lower, ".github/workflows/") || strings.HasPrefix(lower, ".gitlab-ci") ||
		strings.HasPrefix(lower, ".circleci/") || base == "jenkinsfile" || base == "azure-pipelines.yml":
		return ContinuousIntegration
	case lockfiles[base] || manifests[base]:
		return Dependencies
	case docExtensions[ext] || strings.HasPrefix(lower, "docs/") || base == "license" || base == "notice":
		return Documentation
	case styleExtensions[ext]:
		return Stylesheets
	case assetExtensions[ext]:
		return Assets
	case sourceExtensions[ext]:
		return SourceCode
	default:
		return Configuration
	}
}

func isTestPath(lower, base string) bool {
	if strings.HasSuffix(base, "_test.go") || strings.Contains(base, ".test.") || strings.Contains(base, ".spec.") ||
		strings.HasPrefix(base, "test_") || strings.HasSuffix(strings.TrimSuffix(base, path.Ext(base)), "_test") {
		return true
	}
	for _, dir := range []string{"test/", "tests/", "__tests__/", "testdata/", "e2e/", "spec/"} {
		if strings.HasPrefix(lower, dir) || strings.Contains(lower, "/"+dir) {
			return true
		}
	}
	return false
}
