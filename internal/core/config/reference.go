package config

import (
	"fmt"
	"reflect"
	"strings"
)

// Reference returns the Markdown reference of every setting key — type,
// default, allowed values, environment variable, description — generated
// from Settings like the JSON Schema, so that the documentation never lags
// behind the code. tools/gen writes it to docs/reference/settings.md.
func Reference() []byte {
	var b strings.Builder
	b.WriteString("<!-- Code generated by `go run ./tools/gen` from internal/core/config. DO NOT EDIT. -->\n\n")
	b.WriteString("# Settings reference\n\n")
	b.WriteString("Every key of `.github/ship.json`, the user file, presets, contexts and overrides. ")
	b.WriteString("How layers combine is explained in [the configuration guide](configuration.md).\n\n")
	b.WriteString("| Key | Type | Default | Environment variable | Description |\n|---|---|---|---|---|\n")
	defaults := Flatten(Defaults())
	for _, e := range defaults {
		field, _ := structFieldOfKey(e.Key)
		fmt.Fprintf(&b, "| `%s` | %s | `%s` | `%s` | %s |\n",
			e.Key, typeOf(field), e.Value, EnvName(e.Key), escapeCell(strings.TrimSpace(field.Tag.Get("doc"))))
	}
	return []byte(b.String())
}

// typeOf describes a field's type for people: its allowed values, minimum.
func typeOf(f reflect.StructField) string {
	switch f.Type.Kind() {
	case reflect.Bool:
		return "boolean"
	case reflect.Int:
		if m := f.Tag.Get("minimum"); m != "" {
			return "integer ≥ " + m
		}
		return "integer"
	case reflect.Slice:
		if elem := f.Type.Elem(); elem.Kind() == reflect.Struct {
			names := make([]string, 0, elem.NumField())
			for i := range elem.NumField() {
				names = append(names, jsonName(elem.Field(i)))
			}
			return "list of `{" + strings.Join(names, ", ") + "}`"
		}
		if allowed := itemEnumOf(f); len(allowed) > 0 {
			return "list of `" + strings.Join(allowed, "` \\| `") + "`"
		}
		return "list of strings"
	case reflect.Map:
		return reflect.Zero(f.Type).Interface().(mapSetting).typeLabel()
	}
	if allowed := enumOf(f); len(allowed) > 0 {
		return "`" + strings.Join(allowed, "` \\| `") + "`"
	}
	return "string"
}

func escapeCell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ")
}

// structFieldOfKey returns the struct field of a setting key.
func structFieldOfKey(key string) (reflect.StructField, bool) {
	t := reflect.TypeOf(Settings{})
	var field reflect.StructField
	for _, segment := range strings.Split(key, ".") {
		index, ok := fieldsByName(t)[segment]
		if !ok {
			return reflect.StructField{}, false
		}
		field = t.Field(index)
		t = field.Type
	}
	return field, true
}
